"""Generates src/unicode_tables.inc from Python's unicodedata.

    python3 tools/gen_unicode_tables.py > src/unicode_tables.inc

Tables: simple case folding (one character to one), full-width and
half-width forms to their usual ones, canonical combining classes, and
canonical decompositions and compositions for NFC (Hangul syllables are
handled algorithmically and left out).
"""
import sys
import unicodedata


def code(c):
    return "0x%04X" % c


def main():
    case, width, ccc, decompositions, compositions = [], [], [], [], []
    for c in range(sys.maxunicode + 1):
        if 0xD800 <= c <= 0xDFFF:
            continue
        ch = chr(c)
        folded = ch.casefold()
        if len(folded) != 1:
            folded = ch.lower()
        if len(folded) == 1 and folded != ch:
            case.append((c, ord(folded)))
        if 0xFF00 <= c <= 0xFFEF:
            normal = unicodedata.normalize("NFKC", ch)
            if len(normal) == 1 and normal != ch:
                width.append((c, ord(normal)))
        cc = unicodedata.combining(ch)
        if cc:
            ccc.append((c, cc))
        if 0xAC00 <= c <= 0xD7A3:
            continue
        mapping = unicodedata.decomposition(ch)
        if not mapping or mapping.startswith("<"):
            continue
        parts = [int(p, 16) for p in mapping.split()]
        decompositions.append((c, parts[0], parts[1] if len(parts) > 1 else 0))
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == ch:
            compositions.append((parts[0], parts[1], c))
    compositions.sort()

    out = sys.stdout
    out.write("// Generated by tools/gen_unicode_tables.py from Unicode %s (Python's\n"
              "// unicodedata). Do not edit.\n\n" % unicodedata.unidata_version)

    def table(name, kind, rows):
        out.write("const %s %s[] = {\n" % (kind, name))
        line = "   "
        for row in rows:
            item = " {" + ", ".join(code(v) for v in row) + "},"
            if len(line) + len(item) > 99:
                out.write(line + "\n")
                line = "   "
            line += item
        out.write(line + "\n};\n\n")

    table("kCaseFolding", "CodePair", case)
    table("kWidthFolding", "CodePair", width)
    table("kCombiningClasses", "CodePair", ccc)
    table("kDecompositions", "CodeTriple", decompositions)
    table("kCompositions", "CodeTriple", compositions)


if __name__ == "__main__":
    main()
